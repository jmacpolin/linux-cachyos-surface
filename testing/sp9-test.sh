# load

pkg_temp() {  # package temperature in °C
    local h l
    for h in /sys/class/hwmon/hwmon*; do
        [ "$(readf "$h/name")" = coretemp ] || continue
        for l in "$h"/temp*_label; do
            [ "$(readf "$l")" = "Package id 0" ] && { awk '{ printf "%d", $1 / 1000 }' "${l%_label}_input"; return; }
        done
    done
    for h in /sys/class/thermal/thermal_zone*; do
        [ "$(readf "$h/type")" = x86_pkg_temp ] && { awk '{ printf "%d", $1 / 1000 }' "$h/temp"; return; }
    done
    echo 0
}

fan_rpm() { cat /sys/class/hwmon/hwmon*/fan*_input 2>/dev/null | sort -n | tail -1 | grep . || echo 0; }

avg_mhz() { cat /sys/devices/system/cpu/cpu*/cpufreq/scaling_cur_freq 2>/dev/null | awk '{ s += $1; n++ } END { if (n) printf "%d", s / n / 1000; else print 0 }'; }

rapl_uj() { asroot cat /sys/class/powercap/intel-rapl:0/energy_uj 2>/dev/null || echo 0; }

cmd_load() {
    local secs=${1:-60} orig choices p e0 e1 t0 t1 tmax fmax msum n watts a end
    need_sudo
    section load "CPU load per platform profile, ${secs}s each ($(date '+%F %H:%M'))"
    if [ ! -w /sys/firmware/acpi/platform_profile ] && [ ! -r /sys/firmware/acpi/platform_profile ]; then
        result SKIP "Platform profiles" "/sys/firmware/acpi/platform_profile missing"; write_summary; return
    fi
    ac_online || info "WARNING: not on AC power; results will be limited by battery power limits."
    orig=$(readf /sys/firmware/acpi/platform_profile); RESTORE_PROFILE=$orig
    choices=$(readf /sys/firmware/acpi/platform_profile_choices)
    printf 'profile\tavg_pkg_watts\tmax_temp_c\tmax_fan_rpm\tavg_mhz\n' > "$OUT/load.tsv"
    for p in $choices; do
        printf '%s' "$p" | asroot tee /sys/firmware/acpi/platform_profile >/dev/null 2>&1 || { result WARN "Profile $p" "could not set"; continue; }
        info "  profile $p: idle 10 s, then ${secs}s of load..."
        sleep 10
        LOAD_PIDS=
        if have stress-ng; then stress-ng --cpu 0 --timeout "${secs}s" --quiet & LOAD_PIDS=$!
        else for _ in $(seq 1 "$(nproc)"); do ( while :; do :; done ) & LOAD_PIDS+="$! "; done; fi
        e0=$(rapl_uj); t0=$(date +%s.%N); tmax=0; fmax=0; msum=0; n=0
        end=$(( $(date +%s) + secs ))
        while [ "$(date +%s)" -lt "$end" ]; do
            sleep 2
            a=$(pkg_temp); [ "$a" -gt "$tmax" ] && tmax=$a
            a=$(fan_rpm); [ "$a" -gt "$fmax" ] && fmax=$a
            msum=$((msum + $(avg_mhz))); n=$((n + 1))
        done
        e1=$(rapl_uj); t1=$(date +%s.%N)
        # shellcheck disable=SC2086
        { kill $LOAD_PIDS; wait $LOAD_PIDS; } 2>/dev/null; LOAD_PIDS=
        watts=$(awk -v a="$e0" -v b="$e1" -v s="$t0" -v t="$t1" 'BEGIN { if (b > a && t > s) printf "%.1f", (b - a) / 1000000 / (t - s); else print "?" }')
        printf '%s\t%s\t%s\t%s\t%s\n' "$p" "$watts" "$tmax" "$fmax" "$((n ? msum / n : 0))" >> "$OUT/load.tsv"
        result INFO "Profile $p under load" "${watts} W package, max ${tmax} C, max fan ${fmax} rpm, avg $((n ? msum / n : 0)) MHz"
        info "  cooling down 20 s..."; sleep 20
    done
    printf '%s' "$orig" | asroot tee /sys/firmware/acpi/platform_profile >/dev/null 2>&1; RESTORE_PROFILE=
    local wmin wmax
    wmin=$(awk -F'\t' 'NR > 1 && $2 != "?" { print $2 }' "$OUT/load.tsv" | sort -n | head -1)
    wmax=$(awk -F'\t' 'NR > 1 && $2 != "?" { print $2 }' "$OUT/load.tsv" | sort -n | tail -1)
    if [ -n "$wmin" ] && awk -v a="$wmin" -v b="$wmax" 'BEGIN { exit !(b >= a * 1.1) }'; then
        result PASS "Platform profiles change power limits" "${wmin} W to ${wmax} W"
    elif [ -n "$wmin" ]; then
        result WARN "Platform profiles change power limits" "${wmin} W to ${wmax} W (no real difference)"
    else
        result SKIP "Platform profiles change power limits" "no package power readings"
    fi
    if awk -F'\t' 'NR > 1 && $4 > 0 { found = 1 } END { exit !found }' "$OUT/load.tsv"; then result PASS "Fan spins up under load"
    else result WARN "Fan spins up under load" "fan never reported above 0 rpm"; fi
    write_summary
}

