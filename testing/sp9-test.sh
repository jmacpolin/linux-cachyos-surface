# suspend

# Seconds the system actually spent suspended, from the kernel's PM messages
# after a given epoch (falls back to the caller's wall-clock estimate).
suspended_seconds() {
    asroot journalctl -k --no-pager -o short-unix --no-hostname --since="@$1" 2>/dev/null \
        | awk '/PM: suspend entry/ { e = $1 } /PM: suspend exit/ { if (e) { printf "%d", $1 - e; exit } }'
}

wait_for_resume() {  # wait_for_resume SUCCESS_BEFORE FAIL_BEFORE TIMEOUT -> 0 resumed, 1 failed, 2 timed out
    local i=0 s f
    while [ "$i" -lt "$3" ]; do
        sleep 1; i=$((i + 1))
        s=$(readf /sys/power/suspend_stats/success); f=$(readf /sys/power/suspend_stats/fail)
        [ "${s:-0}" -gt "$1" ] && return 0
        [ "${f:-0}" -gt "$2" ] && return 1
    done
    return 2
}

cmd_suspend() {
    local nosusp=0 args=() a
    for a in "$@"; do [ "$a" = --no-suspend ] && nosusp=1 || args+=("$a"); done
    local cycles=${args[0]:-10} secs=${args[1]:-60}
    need_sudo
    local tsv="$OUT/suspend.tsv" i before after s0 f0 t0 t1 rc susp hw res woke wakeirq newwarn issues ok=0 resid_sum=0 resid_n=0 problems=""
    local hw0 hw1 slp0 slp1 slp hw_total=0
    section suspend "Suspend/resume: $cycles cycles of ${secs}s ($(date '+%F %H:%M'))"
    if [ "$nosusp" = 1 ]; then info "  (--no-suspend: running the checks without suspending)"; fi
    printf 'cycle\tresult\trtc_wake\tsuspended_s\thw_sleep_s\tslp_s0_s\tresidency_pct\twake_irq\tnew_warnings\tbefore\tafter\n' > "$tsv"
    : > "$OUT/suspend-warnings.txt"
    for i in $(seq 1 "$cycles"); do
        before=$(device_state)
        s0=$(readf /sys/power/suspend_stats/success); f0=$(readf /sys/power/suspend_stats/fail)
        hw0=$(readf /sys/power/suspend_stats/total_hw_sleep)
        slp0=$(asroot cat /sys/kernel/debug/pmc_core/slp_s0_residency_usec 2>/dev/null)
        t0=$(date +%s)
        info "  cycle $i/$cycles: suspending for ${secs}s..."
        if [ "$nosusp" = 1 ]; then
            sleep 2; rc=0
        else
            asroot rtcwake -m no -s "$secs" >/dev/null 2>&1
            if systemctl suspend; then
                wait_for_resume "${s0:-0}" "${f0:-0}" $((secs + 900)); rc=$?
            else
                rc=3
            fi
        fi
        t1=$(date +%s)
        # let devices, iptsd and the network come back
        for _ in $(seq 1 30); do
            sleep 1
            { [ "$(state_get "$before" iptsd)" = 0 ] || iptsd_active; } \
                && { [ "$(state_get "$before" wifi)" = 0 ] || wifi_up; } && break
        done
        sleep 3
        after=$(device_state)
        susp=$(suspended_seconds "$t0"); [ -z "$susp" ] && susp=$((t1 - t0))
        hw1=$(readf /sys/power/suspend_stats/total_hw_sleep)
        hw=$(awk -v a="${hw0:-0}" -v b="${hw1:-0}" 'BEGIN { printf "%d", (b - a) / 1000000 }')
        hw_total=$((hw_total + hw))
        slp1=$(asroot cat /sys/kernel/debug/pmc_core/slp_s0_residency_usec 2>/dev/null)
        slp=$(awk -v a="${slp0:-}" -v b="${slp1:-}" 'BEGIN { if (a != "" && b != "") printf "%d", (b - a) / 1000000; else print "?" }')
        res=$(awk -v h="${hw:-0}" -v s="$susp" 'BEGIN { if (s > 0) printf "%d", 100 * h / s; else print 0 }')
        woke=yes; [ "$nosusp" = 0 ] && [ "$((t1 - t0))" -gt $((secs + 45)) ] && woke=no
        wakeirq=$(readf /sys/power/pm_wakeup_irq)
        classify_warnings "$t0" > "$OUT/.cycle-warn"
        newwarn=$(grep -c '^\[NEW\]' "$OUT/.cycle-warn")
        { echo "== cycle $i"; cat "$OUT/.cycle-warn"; } >> "$OUT/suspend-warnings.txt"
        issues=""
        case $rc in
            1) issues+="suspend failed ($(readf /sys/power/suspend_stats/last_failed_dev)); " ;;
            2) issues+="no resume detected; " ;;
            3) issues+="systemctl suspend refused (inhibited?); " ;;
        esac
        for a in touch iptsd iptsd_inputs cover wifi bt cameras; do
            [ "$(state_get "$before" "$a")" != "$(state_get "$after" "$a")" ] && issues+="$a $(state_get "$before" "$a")->$(state_get "$after" "$a"); "
        done
        [ "$newwarn" -gt 0 ] && issues+="$newwarn new kernel warning(s); "
        if [ "$nosusp" = 0 ] && [ "$rc" = 0 ]; then
            resid_sum=$((resid_sum + res)); resid_n=$((resid_n + 1))
            [ "$res" -lt 50 ] && [ -n "${hw1:-}" ] && issues+="low S0ix residency ${res}%; "
        fi
        if [ -z "$issues" ]; then ok=$((ok + 1)); a=ok; else a="issues: ${issues%; }"; problems+="cycle $i: ${issues%; }. "; fi
        printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$i" "$a" "$woke" "$susp" "${hw:-?}" "$slp" "$res" "${wakeirq:-?}" "$newwarn" "$before" "$after" >> "$tsv"
        info "    $a (suspended ${susp}s, S0ix ${res}%, RTC wake $woke)"
    done
    rm -f "$OUT/.cycle-warn"
    if [ "$ok" = "$cycles" ]; then result PASS "All cycles resumed with devices intact" "$ok/$cycles"
    else result WARN "All cycles resumed with devices intact" "$ok/$cycles clean. $problems"; fi
    if [ "$resid_n" -gt 0 ] && [ "$hw_total" -eq 0 ]; then
        result WARN "Average S0ix residency" "hardware sleep counter never moved: no S0ix at all, or intel_pmc_core isn't reporting (see slp_s0_s in suspend.tsv)"
    elif [ "$resid_n" -gt 0 ]; then
        a=$((resid_sum / resid_n))
        if [ "$a" -ge 80 ]; then result PASS "Average S0ix residency" "${a}%"
        elif [ "$a" -ge 50 ]; then result WARN "Average S0ix residency" "${a}%"
        else result FAIL "Average S0ix residency" "${a}% (deep idle not reached; expect high battery drain)"; fi
    else
        result SKIP "Average S0ix residency" "no real suspend cycles"
    fi
    if grep -q $'\tno\t' "$tsv"; then result INFO "RTC wake from s2idle" "did not wake by itself in at least one cycle"
    elif [ "$nosusp" = 0 ]; then result PASS "RTC wake from s2idle"; fi
    write_summary
}

