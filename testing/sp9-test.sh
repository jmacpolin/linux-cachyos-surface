helper_run() {
    local node f
    case "$1" in
        touch)
            node=$(input_event_node "IPTSD Virtual Touchscreen")
            if have libinput && [ -n "$node" ]; then
                info "    Touch the screen for 10 s..."
                asroot timeout 10 libinput debug-events --device "$node" 2>/dev/null | grep -c TOUCH_DOWN | sed 's/^/    touch-down events: /'
            else info "    (needs libinput and the IPTSD touchscreen device)"; fi ;;
        tablet)
            node=$(input_event_node "Tablet Mode Switch")
            if have libinput && [ -n "$node" ]; then
                info "    Detach or fold the cover within 20 s, then put it back..."
                asroot timeout 20 libinput debug-events --device "$node" 2>/dev/null | grep -i switch | sed 's/^/    /'
            elif have evtest && [ -n "$node" ]; then
                info "    Detach or fold the cover, then press Enter"; read -r _
                asroot evtest --query "$node" EV_SW SW_TABLET_MODE
                if [ $? -eq 10 ]; then info "    tablet mode: ON"; else info "    tablet mode: OFF"; fi
            else info "    (needs libinput or evtest and the tablet mode switch device)"; fi ;;
        frames)
            find "$FRAMES" -maxdepth 1 -type f -printf '    %f\n' 2>/dev/null
            for f in "$FRAMES"/*.png "$FRAMES"/*.ppm; do [ -e "$f" ] && have xdg-open && xdg-open "$f" >/dev/null 2>&1 & done ;;
        qcam)
            if have qcam; then qcam >/dev/null 2>&1; else info "    qcam not installed; try a browser webcam test page or Snapshot/Kamoso."; fi ;;
        speakers)
            if have speaker-test; then speaker-test -c 2 -t wav -l 1 >/dev/null 2>&1
            elif have pw-play && [ -e /usr/share/sounds/alsa/Front_Left.wav ]; then pw-play /usr/share/sounds/alsa/Front_Left.wav; pw-play /usr/share/sounds/alsa/Front_Right.wav
            else info "    (needs speaker-test from alsa-utils)"; fi ;;
        mic)
            f=$(mktemp --suffix=.wav)
            info "    Recording 5 s, speak now..."
            if have pw-record; then timeout 5 pw-record --rate 48000 --channels 1 "$f" 2>/dev/null; pw-play "$f" 2>/dev/null
            elif have arecord; then arecord -q -d 5 -f S16_LE -r 48000 -c 1 "$f"; aplay -q "$f"
            else info "    (needs pw-record or arecord)"; fi
            rm -f "$f" ;;
    esac
}

cmd_checklist() {
    local redo=0 tsv="$OUT/checklist.tsv" entry id sec check how helper ans note status
    [ "${1:-}" = --redo ] && redo=1
    [ "$redo" = 1 ] && rm -f "$tsv"
    touch "$tsv"
    info "Manual checks. Answer y (works), n (broken), p (partly), s (skip / can't test),"
    info "h (run the helper, where offered) or q (quit and continue later)."
    for entry in "${CHECKS[@]}"; do
        IFS='|' read -r id sec check how helper <<< "$entry"
        grep -q "^$id"$'\t' "$tsv" && continue
        info ""
        info "[$sec] $check"
        [ -n "$how" ] && info "    $how"
        while :; do
            if [ -n "$helper" ]; then printf '  y/n/p/s/h/q? '; else printf '  y/n/p/s/q? '; fi
            read -r ans || ans=q
            case "$ans" in
                y|n|p|s) break ;;
                h) [ -n "$helper" ] && helper_run "$helper" ;;
                q) write_checklist; info "Saved; run 'checklist' again to continue."; return 0 ;;
            esac
        done
        note=
        if [ "$ans" != s ] && [ "$ans" != y ]; then printf '  note (what happened): '; read -r note || note=
        elif [ "$ans" = y ]; then printf '  note (optional, Enter to skip): '; read -r note || note=
        fi
        case "$ans" in y) status=works ;; n) status=broken ;; p) status=partial ;; s) status=skipped ;; esac
        printf '%s\t%s\t%s\n' "$id" "$status" "$(printf '%s' "$note" | tr '\t' ' ')" >> "$tsv"
    done
    write_checklist
    info "Checklist complete: $OUT/TESTED.md"
}

write_checklist() {
    local tsv="$OUT/checklist.tsv" entry id sec check how helper status note icon works=0 broken=0 partial=0 skipped=0
    {
        printf '# Manual checks: %s\n\n' "$KREL"
        printf '| Section | Check | Result | Notes |\n|---|---|---|---|\n'
        for entry in "${CHECKS[@]}"; do
            IFS='|' read -r id sec check how helper <<< "$entry"
            status=$(awk -F'\t' -v i="$id" '$1 == i { print $2 }' "$tsv" | tail -1)
            note=$(awk -F'\t' -v i="$id" '$1 == i { print $3 }' "$tsv" | tail -1 | sed 's/|/\\|/g')
            case "$status" in
                works) icon="✅ works"; works=$((works + 1)) ;;
                broken) icon="❌ broken"; broken=$((broken + 1)) ;;
                partial) icon="⚠️ partial"; partial=$((partial + 1)) ;;
                skipped) icon="⚪ skipped"; skipped=$((skipped + 1)) ;;
                *) icon="(not answered)" ;;
            esac
            printf '| %s | %s | %s | %s |\n' "$sec" "$check" "$icon" "$note"
        done
    } > "$OUT/TESTED.md"
    SEC_FILE="$OUT/.summary-checklist.md"
    {
        printf '## Manual checklist\n\n'
        printf '%s works, %s broken, %s partial, %s skipped. Details in TESTED.md.\n' "$works" "$broken" "$partial" "$skipped"
        if [ "$broken" -gt 0 ] || [ "$partial" -gt 0 ]; then
            printf '\n| Check | Result | Notes |\n|---|---|---|\n'
            grep -E '❌|⚠️' "$OUT/TESTED.md" | awk -F' \\| ' '{ print "| " $2 " | " $3 " | " $4 }'
        fi
    } > "$SEC_FILE"
    write_summary
}

