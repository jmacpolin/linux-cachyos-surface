# drain

cmd_drain() {
    local nosusp=0
    [ "${1:-}" = --no-suspend ] && nosusp=1
    need_sudo
    local e0 e1 full c0 c1 t0 t1 s0 f0 hw0 hw1 hours drop rate res
    section drain "Overnight battery drain ($(date '+%F %H:%M'))"
    if ! e0=$(bat_energy) || ! full=$(bat_energy_full); then
        result SKIP "Battery drain while suspended" "no battery energy readings"; write_summary; return
    fi
    ac_online && info "WARNING: the charger is connected; unplug it for a meaningful result."
    c0=$(readf "$(bat_dir)/capacity"); t0=$(date +%s)
    s0=$(readf /sys/power/suspend_stats/success); f0=$(readf /sys/power/suspend_stats/fail)
    hw0=$(readf /sys/power/suspend_stats/total_hw_sleep)
    info "Battery at ${c0}%. Suspending now; leave it (e.g. overnight), then wake it with the power button."
    if [ "$nosusp" = 1 ]; then sleep 3
    elif ! systemctl suspend; then
        result FAIL "Battery drain while suspended" "systemctl suspend refused"; write_summary; return
    else
        wait_for_resume "${s0:-0}" "${f0:-0}" 172800
    fi
    sleep 5
    e1=$(bat_energy); c1=$(readf "$(bat_dir)/capacity"); t1=$(date +%s)
    hw1=$(readf /sys/power/suspend_stats/total_hw_sleep)
    hours=$(awk -v a="$t0" -v b="$t1" 'BEGIN { printf "%.2f", (b - a) / 3600 }')
    drop=$(awk -v a="$e0" -v b="$e1" -v f="$full" 'BEGIN { printf "%.2f", 100 * (a - b) / f }')
    rate=$(awk -v d="$drop" -v s="$((t1 - t0))" 'BEGIN { if (s > 0) printf "%.2f", d * 3600 / s; else print 0 }')
    res=$(awk -v a="${hw0:-0}" -v b="${hw1:-0}" -v s="$((t1 - t0))" 'BEGIN { if (s > 0) printf "%d", 100 * (b - a) / 1000000 / s; else print 0 }')
    {
        echo "start: $(date -d "@$t0" '+%F %H:%M') battery ${c0}% energy ${e0} uWh"
        echo "end:   $(date -d "@$t1" '+%F %H:%M') battery ${c1}% energy ${e1} uWh"
        echo "full:  ${full} uWh"
        echo "elapsed: ${hours} h, drop: ${drop}% of full, rate: ${rate} %/h ($(awk -v r="$rate" 'BEGIN { printf "%.1f", r * 24 }') %/day)"
        echo "S0ix residency over the period: ${res}%"
        echo "suspends during the period: $(( $(readf /sys/power/suspend_stats/success) - ${s0:-0} ))"
    } > "$OUT/drain.txt"
    result INFO "Elapsed" "${hours} h, battery ${c0}% -> ${c1}%"
    if awk -v r="$rate" 'BEGIN { exit !(r <= 0.6) }'; then result PASS "Drain rate while suspended" "${rate} %/h (7.1 estimate: under 0.4 %/h)"
    elif awk -v r="$rate" 'BEGIN { exit !(r <= 1.5) }'; then result WARN "Drain rate while suspended" "${rate} %/h (7.1 estimate: under 0.4 %/h)"
    else result FAIL "Drain rate while suspended" "${rate} %/h (7.1 estimate: under 0.4 %/h)"; fi
    result INFO "S0ix residency over the period" "${res}%"
    write_summary
}

