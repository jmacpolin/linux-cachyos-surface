cmd_cameras() {
    need_sudo
    local dir="$OUT/cameras" idx name props loc rot log t0 frames fps errs last png
    mkdir -p "$dir" "$FRAMES"
    section cameras "Cameras ($(date '+%F %H:%M'))"
    if ! have cam; then
        result SKIP "Camera capture" "cam (libcamera-tools) not installed"
        write_summary; return
    fi
    cam -l 2>/dev/null | sed -n 's/^ *\([0-9][0-9]*\): \(.*\)$/\1|\2/p' > "$dir/.list"
    if [ ! -s "$dir/.list" ]; then
        result FAIL "Camera capture" "libcamera found no cameras"
        write_summary; return
    fi
    info "Point the cameras at something with recognizable up/down (not your face if you'd rather not)."
    info "Each camera captures 60 frames, then 12 more to save one frame."
    while IFS='|' read -r idx name; do
        props=$(cam -c "$idx" -p 2>/dev/null)
        printf '%s\n' "$props" > "$dir/cam$idx-properties.txt"
        loc=$(printf '%s\n' "$props" | sed -n 's/.*Location = \([0-9]*\).*/\1/p' | head -1)
        rot=$(printf '%s\n' "$props" | sed -n 's/.*Rotation = \([0-9]*\).*/\1/p' | head -1)
        case "$loc" in 0) loc=front ;; 1) loc=rear ;; 2) loc=external ;; *) loc="camera $idx" ;; esac
        name=$(printf '%s' "$name" | sed 's/\\/\\\\/g')
        result INFO "$loc camera properties" "$name, rotation ${rot:-?}"
        if [ "$loc" = rear ]; then
            if [ "$rot" = 180 ]; then result PASS "Rear camera reports rotation 180"
            else result FAIL "Rear camera reports rotation 180" "rotation=${rot:-?}"; fi
        fi

        log="$dir/cam$idx-capture.log"
        t0=$(date +%s)
        timeout 45 cam -c "$idx" -C 60 > "$log" 2>&1
        sleep 1
        frames=$(grep -c ' seq: ' "$log")
        fps=$(sed -n 's/.*(\([0-9.]*\) fps).*/\1/p' "$log" | tail -n 40 | awk '$1 > 0 { s += $1; n++ } END { if (n) printf "%.1f", s / n; else print 0 }')
        if [ "$frames" -ge 55 ]; then result PASS "$loc camera streams" "$frames/60 frames, ${fps} fps"
        else result FAIL "$loc camera streams" "$frames/60 frames in 45 s"; fi
        if grep -q 'Camera configuration adjusted' "$log"; then
            result WARN "$loc camera upright without adjustment" "libcamera adjusted the configuration (orientation not achievable?)"
        else
            result PASS "$loc camera upright without adjustment" "libcamera accepted orientation rot0"
        fi
        errs=$(classify_warnings "$t0" | grep '^\[NEW\]' | grep -iE 'time ?out|isys|csi|ov5693|ov13858|ipu|int3472|frame')
        printf '%s\n' "$errs" > "$dir/cam$idx-kernel.log"
        if printf '%s' "$errs" | grep -qiE 'stream stop time ?out|timed out|timeout'; then
            result FAIL "$loc camera: no capture errors in kernel log" "$(printf '%s' "$errs" | grep -iE 'time ?out' | head -1)"
        elif [ -n "$errs" ]; then
            result WARN "$loc camera: no capture errors in kernel log" "$(printf '%s\n' "$errs" | grep -c .) camera-related warning(s), see cameras/cam$idx-kernel.log"
        else
            result PASS "$loc camera: no capture errors in kernel log"
        fi

        rm -f "$FRAMES"/cam"$idx"-*.ppm
        timeout 30 cam -c "$idx" -C 12 --file="$FRAMES/cam$idx-#.ppm" > /dev/null 2>&1
        last=$(find "$FRAMES" -maxdepth 1 -name "cam$idx-*.ppm" -printf '%T@ %p\n' 2>/dev/null | sort -n | tail -1 | cut -d' ' -f2-)
        if [ -n "$last" ]; then
            png="$FRAMES/$loc-camera.png"
            if have magick; then magick "$last" -resize 50% "$png" && rm -f "$FRAMES"/cam"$idx"-*.ppm
            elif have convert; then convert "$last" -resize 50% "$png" && rm -f "$FRAMES"/cam"$idx"-*.ppm
            elif have ffmpeg; then ffmpeg -loglevel error -y -i "$last" -vf scale=iw/2:-1 "$png" && rm -f "$FRAMES"/cam"$idx"-*.ppm
            else png="$FRAMES/$loc-camera.ppm"; mv "$last" "$png"; rm -f "$FRAMES"/cam"$idx"-*.ppm; fi
            result INFO "$loc camera frame saved" "$png (check that it's upright; not added to the report)"
        else
            result WARN "$loc camera frame saved" "no frame written"
        fi
    done < "$dir/.list"
    rm -f "$dir/.list"
    write_summary
}

