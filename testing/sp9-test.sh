usage() { sed -n '2,/^$/{s/^# \{0,1\}//;p}' "${BASH_SOURCE[0]}"; }

main() {
    local cmd=${1:-}
    [ $# -gt 0 ] && shift
    case "$cmd" in
        collect|cameras|suspend|drain|load|checklist|all) ;;
        -h|--help|help|"") usage; exit 0 ;;
        *) echo "Unknown command: $cmd" >&2; usage >&2; exit 2 ;;
    esac
    mkdir -p "$OUT"
    info "Report directory: $OUT"
    case "$cmd" in
        collect) cmd_collect ;;
        cameras) cmd_cameras ;;
        suspend) cmd_suspend "$@" ;;
        drain) cmd_drain "$@" ;;
        load) cmd_load "$@" ;;
        checklist) cmd_checklist "$@" ;;
        all) cmd_collect; cmd_cameras; cmd_checklist; cmd_suspend 10 60 ;;
    esac
    report_hint
}

main "$@"
